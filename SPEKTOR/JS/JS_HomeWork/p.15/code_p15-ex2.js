/* Task:
קלט אורך ורוחב של חדר מלבני. הצג את שטח החדר ואת היקפו.

Input the length and width of a rectangular room. Display the area and the perimeter of the room.
*/

//Solution:
let length = 5;
let width = 3;

let area = length * width;
let perimeter = 2 * (length + width);

console.log(`The area of the room is: ${area}m²`);
console.log(`The perimeter of the room is: ${perimeter}m`);